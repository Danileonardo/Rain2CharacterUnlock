    /// <summary>
    /// Presentación local de las Generated Missions de G8.
    ///
    /// La misión efectiva viaja en el snapshot del host, pero el texto se
    /// resuelve localmente según el idioma del cliente.
    ///
    /// Regla visual USU:
    /// - máximo 2 líneas;
    /// - máximo 50 caracteres por línea;
    /// - objetivo habitual: 43-47 caracteres por línea cuando sea posible.
    /// </summary>
    public static class GeneratedMissionPresentationFormatter
    {
        private const int MaxLineLength = 50;


        public static bool TryResolve(
            SurvivorJsonEntry entry,
            out string missionName,
            out string missionDescription
        )
        {
            return TryResolve(
                entry?.Challenge,
                out missionName,
                out missionDescription
            );
        }


        public static bool TryResolve(
            SurvivorChallengeJson challenge,
            out string missionName,
            out string missionDescription
        )
        {
            missionName = "";
            missionDescription = "";

            if (
                challenge == null ||
                !string.Equals(
                    challenge.Type,
                    "GeneratedMission",
                    StringComparison.OrdinalIgnoreCase
                )
            )
            {
                return false;
            }

            string family =
                challenge.Parameters?
                    .Value<string>("generatedFamily")
                ?? "";

            if (
                string.Equals(
                    family,
                    MissionTemplateFamily.CombatKills.ToString(),
                    StringComparison.OrdinalIgnoreCase
                )
            )
            {
                BuildCombatKillsText(
                    challenge,
                    out missionName,
                    out missionDescription
                );
                return true;
            }

            if (
                string.Equals(
                    family,
                    MissionTemplateFamily.Execution.ToString(),
                    StringComparison.OrdinalIgnoreCase
                )
            )
            {
                BuildExecutionText(
                    challenge,
                    out missionName,
                    out missionDescription
                );
                return true;
            }

            if (
                string.Equals(
                    family,
                    MissionTemplateFamily.HealingSupport.ToString(),
                    StringComparison.OrdinalIgnoreCase
                )
            )
            {
                BuildHealingSupportText(
                    challenge,
                    out missionName,
                    out missionDescription
                );
                return true;
            }

            if (
                string.Equals(
                    family,
                    MissionTemplateFamily.ResourceMastery.ToString(),
                    StringComparison.OrdinalIgnoreCase
                )
            )
            {
                BuildResourceMasteryText(
                    challenge,
                    out missionName,
                    out missionDescription
                );
                return true;
            }

            if (
                string.Equals(
                    family,
                    MissionTemplateFamily.MeleeCombat.ToString(),
                    StringComparison.OrdinalIgnoreCase
                )
            )
            {
                BuildMeleeCombatText(
                    challenge,
                    out missionName,
                    out missionDescription
                );
                return true;
            }

            if (
                string.Equals(
                    family,
                    MissionTemplateFamily.ProjectileCombat.ToString(),
                    StringComparison.OrdinalIgnoreCase
                )
            )
            {
                BuildProjectileCombatText(
                    challenge,
                    out missionName,
                    out missionDescription
                );
                return true;
            }

            bool spanish = IsSpanishLanguage();

            missionName =
                spanish
                    ? "Misión generada"
                    : "Generated Mission";

            missionDescription =
                spanish
                    ? "Completa la misión generada por USU."
                    : "Complete the mission generated by USU.";

            return true;
        }


        private static void BuildCombatKillsText(
            SurvivorChallengeJson challenge,
            out string missionName,
            out string missionDescription
        )
        {
            bool spanish = IsSpanishLanguage();
            GetPrimaryValues(
                challenge,
                out int amount,
                out string resetScope,
                out List<string> performers
            );

            if (spanish)
            {
                missionName = "Cacería calculada";
                missionDescription =
                    $"Derrota {amount} enemigos;\n" +
                    (IsStage(resetScope)
                        ? "hazlo en un sector."
                        : "hazlo en una partida.");
                return;
            }

            missionName = "Calculated Hunt";
            missionDescription =
                $"Defeat {amount} enemies;\n" +
                (IsStage(resetScope)
                    ? "do it in one stage."
                    : "do it in one run.");
        }


        private static void BuildExecutionText(
            SurvivorChallengeJson challenge,
            out string missionName,
            out string missionDescription
        )
        {
            bool spanish = IsSpanishLanguage();
            GetPrimaryValues(
                challenge,
                out int amount,
                out string resetScope,
                out List<string> performers
            );

            if (spanish)
            {
                missionName = "Ejecución calculada";

                string line1 =
                    $"Consigue {amount} bajas con habilidades de ejecución;";

                if (line1.Length > MaxLineLength)
                {
                    line1 =
                        $"Consigue {amount} bajas con técnicas de ejecución;";
                }

                string prefix =
                    IsStage(resetScope)
                        ? "hazlas en un sector"
                        : "hazlas en una partida";

                missionDescription =
                    line1 + "\n" +
                    BuildScopeOnlyLine(prefix);
                return;
            }

            missionName = "Calculated Execution";

            string englishLine1 =
                $"Get {amount} kills with execution-capable skills;";

            if (englishLine1.Length > MaxLineLength)
            {
                englishLine1 =
                    $"Get {amount} kills with execution skills;";
            }

            string englishPrefix =
                IsStage(resetScope)
                    ? "in one stage"
                    : "in one run";

            missionDescription =
                englishLine1 + "\n" +
                BuildScopeOnlyLine(englishPrefix);
        }


