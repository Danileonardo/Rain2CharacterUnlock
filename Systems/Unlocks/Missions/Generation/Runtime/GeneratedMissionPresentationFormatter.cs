        private static void GetPrimaryValues(
            SurvivorChallengeJson challenge,
            out int amount,
            out string resetScope,
            out List<string> performers
        )
        {
            MissionObjective objective =
                FindPrimaryObjective(
                    challenge?.Mission
                );

            amount =
                Math.Max(
                    1,
                    (int)Math.Round(
                        objective?.Amount ??
                        challenge?.Parameters?.Value<double?>("amount") ??
                        1d
                    )
                );

            resetScope =
                objective?.ResetScope
                ?? challenge?.Parameters?.Value<string>("resetScope")
                ?? "Run";

            performers =
                ResolvePerformerDisplayNames(
                    objective
                );
        }


        private static bool IsStage(string resetScope)
        {
            return string.Equals(
                resetScope,
                "Stage",
                StringComparison.OrdinalIgnoreCase
            );
        }


        private static MissionObjective FindPrimaryObjective(
            MissionDefinition mission
        )
        {
            if (
                mission?.Routes == null ||
                mission.Routes.Count == 0
            )
            {
                return null;
            }

            for (int routeIndex = 0;
                routeIndex < mission.Routes.Count;
                routeIndex++)
            {
                MissionRoute route =
                    mission.Routes[routeIndex];

                IReadOnlyList<MissionObjective> objectives =
                    route?.GetEffectiveObjectives();

                if (
                    objectives != null &&
                    objectives.Count > 0
                )
                {
                    return objectives[0];
                }
            }

            return null;
        }


        private static List<string> ResolvePerformerDisplayNames(
            MissionObjective objective
        )
        {
            List<string> result =
                new List<string>();

            if (objective?.Conditions == null)
            {
                return result;
            }

            HashSet<string> seenBodies =
                new HashSet<string>(
                    StringComparer.OrdinalIgnoreCase
                );

            for (int conditionIndex = 0;
                conditionIndex < objective.Conditions.Count;
                conditionIndex++)
            {
                MissionCondition condition =
                    objective.Conditions[conditionIndex];

                if (
                    condition == null ||
                    !string.Equals(
                        condition.Type,
                        "AllowedPerformerSkill",
                        StringComparison.OrdinalIgnoreCase
                    )
                )
                {
                    continue;
                }

                JArray options =
                    condition.Parameters?["options"]
                    as JArray;

                if (options == null)
                {
                    continue;
                }

                for (int optionIndex = 0;
                    optionIndex < options.Count;
                    optionIndex++)
                {
                    JObject option =
                        options[optionIndex]
                        as JObject;

                    string bodyName =
                        option?.Value<string>("body")?
                            .Trim()
                        ?? "";

                    if (
                        string.IsNullOrWhiteSpace(bodyName) ||
                        !seenBodies.Add(bodyName)
                    )
                    {
                        continue;
                    }

                    result.Add(
                        ResolveBodyDisplayName(
                            bodyName
                        )
                    );
                }
            }

            result.Sort(
                StringComparer.CurrentCultureIgnoreCase
            );

            return result;
        }


        private static string ResolveBodyDisplayName(
            string bodyName
        )
        {
            if (
                MissionProfileService.TryGetByBodyName(
                    bodyName,
                    out MissionProfile profile
                ) &&
                profile != null &&
                !string.IsNullOrWhiteSpace(profile.DisplayName)
            )
            {
                return profile.DisplayName.Trim();
            }

            SurvivorDef[] survivors =
                SurvivorCatalog.survivorDefs;

            if (survivors != null)
            {
                for (int i = 0; i < survivors.Length; i++)
                {
                    SurvivorDef survivor =
                        survivors[i];

                    if (
                        survivor?.bodyPrefab == null ||
                        !string.Equals(
                            survivor.bodyPrefab.name,
                            bodyName,
                            StringComparison.OrdinalIgnoreCase
                        )
                    )
                    {
                        continue;
                    }

                    string localized =
                        Language.GetString(
                            survivor.displayNameToken
                        );

                    if (!string.IsNullOrWhiteSpace(localized))
                    {
                        return localized.Trim();
                    }
                }
            }

            return bodyName.EndsWith(
                "Body",
                StringComparison.OrdinalIgnoreCase
            )
                ? bodyName.Substring(
                    0,
                    bodyName.Length - 4
                )
                : bodyName;
        }


        private static string BuildScopeOnlyLine(
            string prefix
        )
        {
            string normalizedPrefix =
                prefix?.Trim() ?? "";

            if (string.IsNullOrWhiteSpace(normalizedPrefix))
            {
                return "";
            }

            return normalizedPrefix + ".";
        }


        private static string BuildPerformerLine(
            string prefix,
            List<string> performers,
            bool spanish,
            string spanishRole,
            string englishRole
        )
        {
            string normalizedPrefix =
                prefix?.Trim() ?? "";

            if (
                performers != null &&
                performers.Count > 0
            )
            {
                string joined =
                    string.Join(
                        "/",
                        performers.ToArray()
                    );

                string fullLine =
                    normalizedPrefix +
                    " - " +
                    joined +
                    ".";

                if (fullLine.Length <= MaxLineLength)
                {
                    return fullLine;
                }

                if (performers.Count > 2)
                {
                    string compact =
                        performers[0] +
                        "/" +
                        performers[1] +
                        "/+" +
                        (performers.Count - 2);

                    string compactLine =
                        normalizedPrefix +
                        " - " +
                        compact +
                        ".";

                    if (compactLine.Length <= MaxLineLength)
                    {
                        return compactLine;
                    }
                }
            }

            string role =
                spanish
                    ? spanishRole
                    : englishRole;

            string fallback =
                normalizedPrefix +
                " " +
                role +
                ".";

            if (fallback.Length <= MaxLineLength)
            {
                return fallback;
            }

            return spanish
                ? role + "."
                : role + ".";
        }


        private static bool IsSpanishLanguage()
        {
            string language =
                Language.currentLanguageName
                ?? "";

            return language.StartsWith(
                "es",
                StringComparison.OrdinalIgnoreCase
            );
        }
